/** Maps a VS Code locale (`zh-cn`, `pt-br`, `de`) onto one of the ten shipped panels. */
export function resolveLang(setting: string, vscodeLang: string): Lang {
  if ((LANGS as readonly string[]).includes(setting)) return setting as Lang;
  const full = vscodeLang.toLowerCase();
  if ((LANGS as readonly string[]).includes(full)) return full as Lang;
  const base = full.split("-")[0];
  const alias: Record<string, Lang> = { zh: "zh-cn", pt: "pt-br" };
  if (alias[base]) return alias[base];
  return (LANGS as readonly string[]).includes(base) ? (base as Lang) : "en";
}
